/**
 * Regenerates `src/heist/heist.dictionary.ts` from a system word list.
 *
 * Run from the backend root:
 *
 *     node scripts/build-dictionary.mjs [path-to-word-list]
 *
 * Defaults to Debian's `american-english` (the `wamerican` package). The output
 * is committed, so this only needs running when the rules below change — the
 * app never reads a system dictionary at runtime, where one may not exist.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import {
  RegExpMatcher,
  englishDataset,
  englishRecommendedTransformers,
} from 'obscenity';

const SOURCE = process.argv[2] ?? '/usr/share/dict/american-english';
const OUT = 'src/heist/heist.dictionary.ts';

/** Matches `ModerationService` so the two never disagree about a word. */
const matcher = new RegExpMatcher({
  ...englishDataset.build(),
  ...englishRecommendedTransformers,
});

const entries = readFileSync(SOURCE, 'utf8')
  .split('\n')
  // Plain lowercase words only: proper nouns, contractions and hyphenated
  // entries can't be spelled from a pool of loose letters in the first place.
  .filter((word) => /^[a-z]{4,11}$/.test(word));

const unique = [...new Set(entries)].sort();
const clean = unique.filter((word) => !matcher.hasMatch(word));

const header = `/**
 * The word list Heist claims are checked against.
 *
 * Generated by scripts/build-dictionary.mjs — edit that, not this. Derived from
 * Debian's SCOWL-based \`american-english\` list, reduced to plain 4–11 letter
 * lowercase entries.
 *
 * Words the shared profanity filter flags are dropped at generation time rather
 * than warned about at claim time. Every other game in Cahoots warns and lets
 * the player decide, but those all involve someone *choosing* what to send.
 * Heist is a three-minute race, and a confirmation dialog mid-sprint would cost
 * the round it interrupted — so here the word simply isn't in the dictionary
 * and the claim bounces like any other non-word.
 *
 * Stored as one space-separated string and split into a Set at startup: ${clean.length}
 * quoted array elements is megabytes of parsed source for a table that only
 * ever answers "is this a word".
 */
export const HEIST_DICTIONARY_RAW =
  '`;

writeFileSync(OUT, `${header}${clean.join(' ')}';\n`);

console.log(
  `${OUT}: kept ${clean.length} of ${unique.length} words ` +
    `(dropped ${unique.length - clean.length} flagged)`,
);
